QUICK START
1. Enter the exact game name and numeric Steam server AppID.
2. Enter the server executable path relative to the installed server folder.
3. Enter only the command text that comes after the executable. Use the supported tags below where Synix must insert a user's setting.
4. Choose how the game gets its configuration file. A managed mode requires a complete, working configuration file—not a partial example.
5. Select Validate & Preview. Fix every reported problem before saving.
6. Save, rebuild Synix, run the automated tests, then test install/start/stop/monitoring for the game.

REQUIRED FIELDS
• Game name: the name users see in Synix.
• Definition ID: unique lowercase ID; Synix creates it from the game name for you.
• Steam AppID: dedicated-server AppID, not always the client game AppID.
• SteamCMD app configuration: normally blank. Shared GoldSrc AppID 90 games use the verified form '90 mod folder', such as '90 mod cstrike'. Synix accepts only this safe form.
• Executable: for example Binaries\Win64\Server.exe. Do not include the install folder.
• Ports: verified default game and query ports.
• Maps and game modes: enter one exact game value per line. These populate the choices shown while creating or editing a server.

LAUNCH ARGUMENTS
Do not enter the executable itself. Keep the game's fixed flags as normal text and insert tags only for values controlled by Synix.
Example: -port {port} -queryport {query} -name "{ServerName}" -maxplayers {MaxPlayers}

SUPPORTED ARGUMENT TAGS
[LAUNCH_ARGUMENT_TAGS]

RCON RECIPE
Put {rcon} in the launch arguments where the optional RCON command belongs. In RCON syntax, use:
[RCON_ARGUMENT_TAGS]
Example RCON syntax: +rcon.port {rcon_port} +rcon.password "{rcon_pass}"

CONFIGURATION BEHAVIOR
• Not verified yet: Synix does not manage a config file.
• Game creates it after first start: use a complete captured config as the editing and repair template.
• Synix creates it from a template: Synix places the complete config before first start.
• Launch arguments only: the game does not require a managed config for these settings.

CONFIGURATION TEMPLATE TAGS
{ServerName}, {Password}, {HasPassword}, {AdminPassword}, {MaxPlayers}, {Port}, {QueryPort}, {RCONPort}, {RCONPassword}, {EnableRcon}, {Identity}, {WorldName}, {WorldSeed}, {WorldSize}, {AppPort}, {LocalIP}, {PublicIP}, {IsPvp}, {IsPve}, {GameMode}
{HasPassword} writes the definition's true value when a server password exists and its false value when the password is empty.
Use Add configuration files when a server needs more than one file. Select each complete source file, then edit its Installed location in the table so the path is relative to the server folder. Synix validates, embeds, writes, repairs, and upgrades every listed file together.

REQUIRED USER-SUPPLIED FILES
Enter one safe path per line, relative to the installed server folder. Required files block startup until present; optional files are imported when found but never block startup.
When required files come from the normal game, explain every user step in Setup instructions. Synix never downloads, bypasses ownership, or redistributes licensed player files.
External data folder is the folder name Synix may look for under the user's Documents folders. Leave it empty when the user must copy the files manually.

FIRST-START WARNING AND ICON
Enable the warning when users must complete setup before the first launch. Write the exact steps and identify anything the user must obtain from their own game installation.
Icon URL is optional and must use HTTPS. Synix falls back to the installed server executable icon when it is blank.

REVISIONS AND SAFETY
Start new definitions and templates at revision 1. Increase definition revision whenever the game definition changes. Increase template revision only when the managed config layout changes. Synix refuses an overwrite without a higher revision and preserves upgrade backups.

POST-INSTALL OPTION
Enable Steam runtime copying only when the server has been verified to require it. The target must be a relative folder inside that server installation. Synix copies only its three allowlisted Steam runtime DLLs.

RUNTIME REQUIREMENTS
Set minimum system RAM to 0 when the game has no verified minimum. Hardware and Windows-runtime checks explain missing requirements before setup and block an unsafe launch; they do not change Windows settings.
Select a .NET Framework or Visual C++ runtime only when the game's official requirements identify it. Synix checks the Windows registry but never installs or downloads prerequisites silently.
Hyper-V requires Windows Professional or higher, so selecting Hyper-V also selects that Windows requirement.

LAUNCH BEHAVIOR
Use normal process tracking for standard dedicated servers. External deployment is only for a launcher, virtual machine, or other deployment that owns the server lifecycle; it automatically disables query monitoring.
Enable Required visible manager for games whose official server manager must stay open. This overrides the user's global hide-console preference only for that definition.
Elevated launch is supported only for .exe, .bat, and .cmd launch files. Enable launch-file export only when the user can safely create and run a reviewed launch file outside Synix.
The ready message is shown after the game's special readiness checks succeed. These fields select built-in, allowlisted Synix behavior and cannot run arbitrary scripts or plugins.

LOG DISCOVERY
Enter safe paths relative to the installed server folder. Use * for one path segment or file name and ** for nested folders. Supported placeholders are {Identity}, {ServerName}, {WorldName}, {Port}, and {QueryPort}.
Examples: logs\latest.log, Saved\Logs\*.log, profiles\{Identity}\logs\**\*.log. Synix searches these paths only when the user asks to open the newest game log.
